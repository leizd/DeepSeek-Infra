// Simple lowercase and final-sigma context observed across every codepoint
// with CPython 3.12.12 (Unicode 15.0.0). U+0130's unconditional expansion
// and U+03A3's final-sigma rule are applied by Text::lower.
#[derive(Clone, Copy)]
pub(super) enum CaseContext {
    Boundary,
    Cased,
    Ignorable,
}

pub(super) fn case_context(value: u32) -> CaseContext {
    let at = CASE_CONTEXT.partition_point(|&(_, end, _)| end < value);
    CASE_CONTEXT
        .get(at)
        .filter(|&&(start, _, _)| start <= value)
        .map_or(CaseContext::Boundary, |&(_, _, context)| context)
}

pub(super) fn lower_simple(value: u32) -> u32 {
    LOWERCASE
        .binary_search_by_key(&value, |&(upper, _)| upper)
        .map_or(value, |at| LOWERCASE[at].1)
}

